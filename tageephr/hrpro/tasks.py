"""مهام مجدولة لنظام Tageep HRMS."""
from __future__ import annotations

from datetime import date

import frappe

from . import engine, files, store
from .utils import month_range, num, today_iso, uid


def daily_backup():
	"""نسخة أمان مشفرة يومية + ترحيل سجلات التدقيق القديمة."""
	try:
		state = store.load_state()
		result = files.create_backup(state, auto=True)
		frappe.logger("tageephr").info("نسخة احتياطية يومية: %s (%s بايت)" % (result["name"], result["size"]))
		engine.add_audit(state, {"userId": "system", "userName": "النظام", "action": "backup",
		                         "module": "settings", "collection": "settings", "recordId": "",
		                         "details": "نسخة احتياطية يومية تلقائية: %s" % result["name"], "ip": ""})
		store.commit(state)
	except Exception:
		frappe.log_error(frappe.get_traceback(), "TageepHR daily backup")


def auto_generate_payslips():
	"""توليد كشوف رواتب الشهر تلقائياً في اليوم المحدد بإعدادات الرواتب.

	لا يشترط وجود حضور أو بصمات أو تأخير: الكشف يُنشأ من الراتب الأساسي
	والبدلات والمستحقات، والخصومات تُحسب فقط من بيانات الحضور الموجودة فعلاً
	(بدون توليد أيام غياب وهمية).
	"""
	try:
		state = store.load_state()
		ps = state.get("payrollSettings") or {}
		if (ps.get("payslipMode") or "auto") != "auto":
			return "manual mode"
		day = int(num(ps.get("autoGenerateDay")) or 25)
		if date.today().day != day:
			return "not today"

		year, month = date.today().year, date.today().month
		range_ = month_range(year, month)
		period = next((p for p in state.get("payrollPeriods") or []
		               if num(p.get("month")) == month and num(p.get("year")) == year), None)
		if not period:
			period = {"id": uid("pp_"), "name": "رواتب %s/%s" % (month, year),
			          "month": month, "year": year, "fromDate": range_["from"], "toDate": range_["to"],
			          "status": "open", "createdBy": "system", "createdAt": engine._now()}
			state.setdefault("payrollPeriods", []).append(period)
		if period.get("status") == "closed":
			return "period closed"

		employees = [e for e in state.get("employees") or [] if engine.employee_in_period(e, period)]
		created = updated = 0
		for emp in employees:
			idx = next((i for i, p in enumerate(state.get("payslips") or [])
			            if p.get("periodId") == period["id"] and p.get("employeeId") == emp["id"]), -1)
			prev = state["payslips"][idx] if idx >= 0 else None
			if prev and prev.get("status") == "paid":
				continue
			slip = engine.compute_employee_payslip(state, emp, period)
			if prev:
				slip.update({"id": prev.get("id"), "status": prev.get("status") or "draft",
				             "createdAt": prev.get("createdAt") or slip.get("createdAt"),
				             "notes": prev.get("notes") or ""})
				state["payslips"][idx] = slip
				updated += 1
			else:
				slip.update({"id": uid("ps_"), "status": "draft", "mode": "auto", "createdBy": "system"})
				state.setdefault("payslips", []).append(slip)
				created += 1

		if period.get("status") == "open" and (created or updated):
			period["status"] = "draft"
		if created or updated:
			engine.add_audit(state, {"userId": "system", "userName": "النظام", "action": "generate",
			                         "module": "payroll", "collection": "payslips", "recordId": period["id"],
			                         "details": "توليد تلقائي لكشوف %s (%s جديد، %s محدّث)" % (period.get("name"), created, updated),
			                         "ip": ""})
			engine.notify(state, {"key": "payroll-auto:%s:%s" % (period["id"], today_iso()), "type": "payroll",
			                      "severity": "success", "title": "توليد تلقائي لكشوف الرواتب",
			                      "message": "%s: %s كشف راتب" % (period.get("name"), created + updated), "link": "#/payroll"})
			store.commit(state)
		return {"period": period.get("name"), "created": created, "updated": updated}
	except Exception:
		frappe.log_error(frappe.get_traceback(), "TageepHR auto payslips")


def nightly_notifications():
	"""فحص الإشعارات الذكية لكل المستخدمين مرة يومياً."""
	try:
		state = store.load_state()
		for user in state.get("users") or []:
			if user.get("disabled"):
				continue
			engine.scan_notifications(state, user)
		store.commit(state)
	except Exception:
		frappe.log_error(frappe.get_traceback(), "TageepHR nightly notifications")
